export const blogPosts: BlogPost[] = [...requestedPosts, ...legacyPosts];

export function getBlogPost(slug: string) {
  return blogPosts.find((post) => post.slug === slug);
}

export function getBlogCategories(post: BlogPost) {
  if (post.categories?.length) return post.categories;
  const text = `${post.slug} ${post.title} ${post.description}`;
  const categories = new Set<string>();
  if (/TOEIC|toeic|Part5|grammar|文法/.test(text)) categories.add('toeic');
  if (/grammar|文法|Part5/.test(text)) categories.add('grammar');
  if (/listening|リスニング|YouTube|動画/.test(text)) categories.add('listening');
  if (/vocabulary|単語/.test(text)) categories.add('vocabulary');
  if (/AI英会話|ai-english|conversation|会話/.test(text)) categories.add('ai_conversation');
  if (/shadowing|speaking|シャドーイング|発音|スピーキング/.test(text)) categories.add('speaking');
  if (/habit|習慣|続かない|やり直し/.test(text)) categories.add('study_habit');
  return Array.from(categories.size ? categories : ['study_habit']);
}
